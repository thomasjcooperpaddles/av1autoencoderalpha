def parse_path(rel_path):
    # guessit reads the whole relative path, so a bare "07.mkv" inside
    # Show/Season 02 still resolves to the right series and episode.
    # falls back to a crude filename parse when guessit is absent.
    try:
        from guessit import guessit
        g = dict(guessit(rel_path))
        kind = "episode" if g.get("type") == "episode" else "movie"
        season, episode = g.get("season"), g.get("episode")
        # A release named "Show.Episode.01" carries an episode number and
        # no season at all, which is normal for single-season anime. With
        # season left None the SxxExx block silently vanished from the
        # output name. Season one is the only sane reading of an episode
        # number with no season beside it.
        if kind == "episode" and episode is not None and season is None:
            season = 1
        # guessit returns a list when a release spans several episodes;
        # take the first so downstream formatting stays simple
        if isinstance(episode, list):
            episode = episode[0] if episode else None
        if isinstance(season, list):
            season = season[0] if season else None
        return {"title": g.get("title") or "",
                "year": g.get("year"),
                "kind": kind,
                "season": season,
                "episode": episode,
                "ep_title": g.get("episode_title") or ""}
    except Exception:
        base = os.path.basename(rel_path)
        stem = os.path.splitext(base)[0]
        m = re.search(r"[sS](\d{1,2})[eE](\d{1,3})", stem)
        y = re.search(r"(19|20)\d{2}", stem)
        title = re.split(r"[sS]\d{1,2}[eE]\d{1,3}|(19|20)\d{2}", stem)[0]
        title = re.sub(r"[._]+", " ", title).strip(" -")
        return {"title": title, "year": int(y.group(0)) if y else None,
                "kind": "episode" if m else "movie",
                "season": int(m.group(1)) if m else None,
                "episode": int(m.group(2)) if m else None,
                "ep_title": ""}


def embedded_ids(info):
    # a remux often carries an IMDb or TMDB id already. an explicit id
    # beats every other signal because it involves no guessing at all.
    tags = {k.lower(): v for k, v in (info.get("tags") or {}).items()}
    out = {}
    for k, v in tags.items():
        v = str(v)
        m = re.search(r"tt\d{7,9}", v)
        if m and "imdb" not in out:
            out["imdb"] = m.group(0)
        if "tmdb" in k and v.strip().isdigit():
            out["tmdb"] = v.strip()
    return out


