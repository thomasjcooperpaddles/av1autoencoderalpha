def strip_tech_suffix(text, codec="AV1"):
    """Remove trailing codec tokens this pipeline appended itself.

    The fallback guard for the idempotency bug in build_name. When TMDB
    gives no episode record, the title comes from guessit reading the
    filename - and if that filename was produced by a previous run it
    ends in the tech suffix, whose resolution part guessit consumes but
    whose codec part it hands back as if it were part of the title.

    Repeats, because a name may already have accumulated several.
    """
    if not text:
        return text
    out = str(text).strip()
    pat = re.compile(r"[\s_\-]+%s$" % re.escape(codec), re.I)
    while True:
        new = pat.sub("", out)
        if new == out:
            return out.strip()
        out = new


def build_name(meta, parsed, franchise, ext=".mkv", codec="AV1",
               height=1080, underscores=True, include_ep_title=True,
               include_tech=True):
    # shape:  Title-(Year)-Franchise-AV1_1080p.ext
    # TV:     Show-(Year)-S05E01-Episode_Title-AV1_1080p.ext
    # any empty field is dropped rather than leaving a dangling separator
    kind = parsed.get("kind", "movie")
    if meta:
        title = meta.get("title") or meta.get("name") or parsed.get("title")
        date = (meta.get("release_date") or meta.get("first_air_date") or "")
        year = date[:4] if date[:4].isdigit() else parsed.get("year")
    else:
        title = parsed.get("title")
        year = parsed.get("year")
    parts = [safe_name(title, underscores)]
    if year:
        parts.append("(%s)" % year)
    if kind == "episode":
        s, e = parsed.get("season"), parsed.get("episode")
        if s is not None and e is not None:
            parts.append("S%02dE%02d" % (int(s), int(e)))
        # TMDB's episode name wins over whatever guessit scraped out of
        # the filename. Two reasons, and the second is the important one:
        #
        # 1. it is authoritative, where a release group's spelling is not
        # 2. WITHOUT it the naming is not idempotent. Running the
        #    metadata pass over its own output made guessit read the
        #    "AV1" out of the tech suffix as part of the episode title,
        #    so the name grew by one "_AV1" on every pass:
        #      Outside_the_Atmosphere
        #      Outside_the_Atmosphere_AV1
        #      Outside_the_Atmosphere_AV1_AV1
        #    A --metadata-only run is meant to be repeatable over a
        #    finished library; this quietly corrupted it instead.
        ep_rec = (meta or {}).get("_episode") or {}
        ep_title = ep_rec.get("name") or strip_tech_suffix(
            parsed.get("ep_title"), codec)
        if include_ep_title and ep_title:
            parts.append(safe_name(ep_title, underscores))
    if franchise:
        parts.append(safe_name(franchise, underscores))
    if include_tech:
        parts.append("%s_%dp" % (safe_name(codec, underscores), int(height)))
    stem = "-".join(x for x in parts if x)
    stem = re.sub(r"-+", "-", stem).strip("-")
    return stem[:170] + ext


