#!/usr/bin/env python3
# ============================================================================
# av1_metadata.py   V0.1   2026-08-01
#
# Identification, naming, and tagging for av1_pipeline.
#
# Nothing in here is required for an encode to succeed. Every function
# degrades to "no answer" rather than raising, because a metadata lookup
# failing must never cost a file that took hours to encode.
#
# Order of work, cheapest first, so the expensive steps are skipped
# whenever a cheaper one already answered:
#   1. parse the relative path      free, no network
#   2. read tags already in the file free, no network
#   3. TMDB lookup, confirmed by runtime and year
#   4. rename and write tags
# ============================================================================

import json
import os
import re
import subprocess
import urllib.parse
import urllib.request
from pathlib import Path

# Every subprocess in this module MUST carry this. The frame verifier
# alone shells out 24 times per file for the samples plus a dozen for
# the reference images; across a few hundred files that is thousands of
# console windows flashing over whatever the operator is doing. The main
# pipeline has always set it; these two calls were missed.
NOWIN = getattr(subprocess, "CREATE_NO_WINDOW", 0)

# Moves with av1_pipeline_v0_1.VERSION, which selftest enforces. This
# string is written into the .info sidecar beside every finished file
# ("generated by av1_pipeline <VERSION>") and into the TMDB User-Agent,
# so while it sat at "0.2" every sidecar in the library named a build
# that stopped existing long before the file was made.
VERSION = "0.256"

TMDB_BASE = "https://api.themoviedb.org/3"
TMDB_IMG = "https://image.tmdb.org/t/p/"
NET_TIMEOUT = 20

# Visual verification. The distance is over a 64-bit difference hash, so
# 0 is identical and 32 is unrelated. 12 is deliberately generous: a
# backdrop is usually the same frame after a different colour grade, and
# a threshold tight enough to reject those would reject real matches
# too. The check only ever raises confidence, never rejects a title, so
# a false positive here costs a line of text rather than a wrong name.
VERIFY_THRESHOLD = 12
# SAMPLE THE FILM DENSELY INSTEAD OF GUESSING AT TIMECODES.
#
# This was 24 frames, each fetched by its own ffmpeg process with its own
# seek - 24 of 133,799 frames, 0.018 pct of the film. If a backdrop IS a
# frame from the film, the chance of one of 24 samples landing on it is
# negligible, and the obvious fix - align the sample to the timecode of
# the reference - is impossible: TMDB's image records carry
# aspect_ratio, file_path, height, width, iso_3166_1, iso_639_1,
# vote_average and vote_count. There is no timecode in the database to
# align to. VERIFIED against the live API on 2026-08-17.
#
# So sample every VERIFY_EVERY_SEC instead, in ONE ffmpeg pass with an
# fps filter. A 74-minute film at 2 s is ~2,200 frames, which costs one
# decode of the file at 9x8 greyscale rather than 2,200 seeks.
VERIFY_EVERY_SEC = 2.0
VERIFY_MAX_FRAMES = 4000    # ceiling, so a long file cannot run away
VERIFY_SAMPLES = 24         # only used when a dense pass is not possible
VERIFY_MAX_IMAGES = 12      # reference images fetched per title
# Centre fraction kept for the crop-tolerant second hash. A backdrop is
# frequently the same frame at a different crop or with the letterboxing
# handled differently, and a difference hash is not crop-invariant: the
# content lands in different cells and every bit changes. Comparing the
# centre 76 pct of both sides as well absorbs that without making the
# hash mushy.
VERIFY_CENTRE = 0.76

# Windows forbids these outright; the rest are stripped because they
# make shell and path handling miserable on every platform.
BANNED_CHARS = '<>:"/\\|?*'
# Franchise tags the user has already put in their own filenames. These
# are matched against the ORIGINAL name before any renaming happens.
FRANCHISE_TAGS = {
    "007": "007", "james_bond": "007", "jamesbond": "007", "bond": "007",
    "mcu": "MCU", "marvel": "MCU",
    "starwars": "Star_Wars", "star_wars": "Star_Wars",
    "startrek": "Star_Trek", "star_trek": "Star_Trek",
    "stargate": "Stargate", "star_gate": "Stargate",
    "dcu": "DCU", "pixar": "Pixar", "ghibli": "Ghibli",
    "lotr": "LOTR", "middleearth": "LOTR",
}

# Runtime agreement bands. PAL speedup is a real and predictable ratio,
# not a mismatch: 24 fps film run at 25 gives exactly 25/24.
PAL_RATIO = 25.0 / 24.0
RUNTIME_TOL = 0.06          # 6 percent, generous enough for trims
PAL_TOL = 0.015


