def safe_name(s, underscores=True):
    # strip anything a filesystem will reject, collapse the runs of
    # punctuation that leaves behind, and optionally use underscores
    # instead of spaces because linux command lines hate spaces
    if not s:
        return ""
    out = "".join((" " if c in BANNED_CHARS else c) for c in str(s))
    out = out.replace("&", "and")
    out = "".join(c for c in out if c.isprintable())
    # "-" is the field separator in the generated name, so a hyphen
    # inside a title would make the result ambiguous to read back
    out = re.sub(r"\s*[-\u2013\u2014]+\s*", " ", out)
    out = out.replace(",", "")
    out = re.sub(r"\s+", " ", out).strip(" .")
    if underscores:
        out = out.replace(" ", "_")
        out = re.sub(r"_+", "_", out).strip("_")
    return out


def find_franchise(original_name):
    # only ever read from the name the user already curated; never
    # guessed from metadata, because "master collection" is not a field
    # any database actually carries
    low = re.sub(r"[^a-z0-9]+", "_", (original_name or "").lower())
    for token, label in FRANCHISE_TAGS.items():
        if re.search(r"(^|_)" + re.escape(token) + r"($|_)", low):
            return label
    return ""


