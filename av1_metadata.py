def tags_xml(meta, parsed, franchise):
    def esc(v):
        return (str(v).replace("&", "&amp;").replace("<", "&lt;")
                .replace(">", "&gt;"))

    simple = []

    def add(name, value):
        if value:
            simple.append("    <Simple><Name>%s</Name><String>%s</String>"
                          "</Simple>" % (name, esc(value)))
    meta = meta or {}
    title = meta.get("title") or meta.get("name") or parsed.get("title")
    date = meta.get("release_date") or meta.get("first_air_date") or ""
    is_ep = parsed.get("kind") == "episode"
    ep = meta.get("_episode") or {}
    # TMDB returns imdb_id at the top level for a MOVIE but only inside
    # external_ids for a TV series, so reading one place silently
    # dropped the IMDB tag from every episode. The .info sidecar always
    # read external_ids, which is why it carried an id the container did
    # not.
    imdb = meta.get("imdb_id") or (meta.get("external_ids") or {}).get(
        "imdb_id")

    add("TITLE", title)
    add("DATE_RELEASED", date[:4] if date else parsed.get("year"))
    add("SUMMARY", meta.get("overview"))
    add("CONTENT_TYPE", "Movie" if not is_ep else "TV")
    if meta.get("id"):
        add("TMDB", ("tv/%s" if is_ep else "movie/%s") % meta["id"])
    add("IMDB", imdb)
    add("COLLECTION", franchise)
    gl = meta.get("genres") or []
    add("GENRE", ", ".join(g.get("name", "") for g in gl) if gl else None)
    if not simple:
        return None

    head = '<?xml version="1.0" encoding="UTF-8"?>\n<Tags>\n'
    tail = '</Tags>\n'

    def block(ttv, lines):
        return ('  <Tag>\n    <Targets><TargetTypeValue>%d'
                '</TargetTypeValue></Targets>\n' % ttv
                + "\n".join(lines) + "\n  </Tag>\n")

    if not is_ep:
        return head + block(50, simple) + tail

    # A series, a season and an episode are three different things.
    # Matroska says so: 70 is the collection, 60 the season, 50 the
    # episode. Flattening them into one 50 block, as this used to, means
    # a player reads the SERIES name as the episode title and every
    # episode of a show ends up looking identical.
    season = parsed.get("season")
    epno = ep.get("episode_number") or parsed.get("episode")
    ep_title = ep.get("name") or parsed.get("ep_title")
    ep_date = ep.get("air_date")
    ep_overview = ep.get("overview")

    out = [block(70, simple)]
    if season is not None:
        out.append(block(60, ['    <Simple><Name>PART_NUMBER</Name>'
                              '<String>%s</String></Simple>'
                              % esc(int(season))]))
    ep_lines = []
    if ep_title:
        ep_lines.append('    <Simple><Name>TITLE</Name><String>%s</String>'
                        '</Simple>' % esc(ep_title))
    if epno is not None:
        ep_lines.append('    <Simple><Name>PART_NUMBER</Name>'
                        '<String>%s</String></Simple>' % esc(int(epno)))
    if ep_date:
        ep_lines.append('    <Simple><Name>DATE_RELEASED</Name>'
                        '<String>%s</String></Simple>' % esc(ep_date))
    if ep_overview:
        ep_lines.append('    <Simple><Name>SUMMARY</Name><String>%s</String>'
                        '</Simple>' % esc(ep_overview))
    if ep_lines:
        out.append(block(50, ep_lines))
    return head + "".join(out) + tail


def write_tags(mkvpropedit, path, title, xml_path=None, cover=None,
               log=None, video_title=None):
    # mkvpropedit edits in place; no remux, no re-encode, seconds even
    # on a very large file
    if not mkvpropedit:
        return False
    cmd = [mkvpropedit, str(path)]
    if title:
        cmd += ["--edit", "info", "--set", "title=%s" % title]
    if video_title is not None:
        # mkvmerge copies the source's video track name straight through,
        # so a fansub release left the finished file with a video track
        # called "[bonkai77]". Every audio and subtitle track already
        # gets a deliberate name from the pipeline; the video track was
        # the only one still carrying whatever the source happened to
        # have. An empty string deletes the property.
        if video_title:
            cmd += ["--edit", "track:v1", "--set", "name=%s" % video_title]
        else:
            cmd += ["--edit", "track:v1", "--delete", "name"]
    if xml_path:
        cmd += ["--tags", "global:%s" % xml_path]
    if cover:
        cmd += ["--add-attachment", str(cover)]
    if len(cmd) <= 2:
        return False
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=300,
                           creationflags=NOWIN)
        if r.returncode != 0 and log:
            log.warning("    tagging failed: %s"
                        % (r.stderr or r.stdout or "")[:200])
        return r.returncode == 0
    except Exception as e:
        if log:
            log.warning("    tagging failed: %s" % e)
        return False
